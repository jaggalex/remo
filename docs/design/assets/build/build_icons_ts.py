"""Write packages/ui/src/icons.ts from icons/icons.json (ADR-181).

The design source is icons.json; icons.ts is its generated copy for the product, so the
two can never disagree. Usage: python3 -I build_icons_ts.py <assets_dir> <icons.ts>
"""
import json, sys

icons = json.load(open(f"{sys.argv[1]}/icons/icons.json"))


def table(key, every=False):
    # The two line tables list every name ("" for a fill-only icon), so the name type is complete.
    rows = [f'  {json.dumps(k)}: {json.dumps(v.get(key) or "")},' for k, v in icons.items() if every or v.get(key)]
    return "\n".join(rows)


out = f"""// Generated by docs/design/assets/build/build_icons_ts.py from docs/design/assets/icons/icons.json.
// Do not edit by hand: change the geometry in build_icons.py and regenerate (ADR-181).
//
// Two drawings per icon: a 24 master (stroke 2) and a separate 16 grid (stroke 1.5) whose
// nodes sit on quarter pixels. A few icons also have a filled part (statuses, lock-on,
// eye-on). Everything is drawn in currentColor.

/** 24 × 24 master, stroke 2; "" when the icon is only a fill. */
export const ICONS = {{
{table("d", True)}
}} as const;

/** The same icons on their own 16 × 16 grid, stroke 1.5. */
export const ICONS_16: Record<IconName, string> = {{
{table("d16", True)}
}};

/** Filled parts on the 24 grid, drawn with fill-rule evenodd. */
export const ICON_FILLS: Partial<Record<IconName, string>> = {{
{table("fill")}
}};

/** Filled parts on the 16 grid. */
export const ICON_FILLS_16: Partial<Record<IconName, string>> = {{
{table("fill16")}
}};

export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];
"""
open(sys.argv[2], "w").write(out)
print("icons.ts:", len(icons))
